/* 날짜 기준으로 매일 한 줄씩 순환 (모든 사용자가 같은 문구를 봄) */
function quoteOfDay(ds){
  ds = ds || todayStr();
  var y = +ds.slice(0,4), m = +ds.slice(5,7), d = +ds.slice(8,10);
  var days = Math.floor(Date.UTC(y, m-1, d) / 86400000);
  var q = QUOTES[((days % QUOTES.length) + QUOTES.length) % QUOTES.length];
  return { text: q[0], by: q[1] };
}
function quoteHtml(){
  var q = quoteOfDay();
  return '<div class="quote-bar"><span class="quote-l">오늘의 한 줄</span>'
    + '<b class="quote-t">' + esc(q.text) + '</b>'
    + '<span class="quote-by">— ' + esc(q.by) + '</span></div>';
}
